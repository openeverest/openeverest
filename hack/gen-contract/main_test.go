func readFile(t *testing.T, root, name string) string {
	t.Helper()

	data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(name))) //nolint:gosec // a file the test wrote
	require.NoError(t, err)
	return string(data)
}

func TestRun(t *testing.T) {
	t.Parallel()

	root := writeRepo(t, testRepo())
	require.NoError(t, run(root))
	assert.Equal(t, "2.0.0-alpha.1.next\n", readFile(t, root, versionFile))
	assert.Equal(t, "2.0.0-alpha.1\n", readFile(t, root, minVersionFile))

	src := readFile(t, root, outputPath)
	fps := testFingerprints(t, testRepo())
	assert.True(t, strings.HasPrefix(src, testHeader+"\n// Code generated by hack/gen-contract. DO NOT EDIT.\n\npackage contract\n"))
	assert.Contains(t, src, "\tVersion = \"2.0.0-alpha.1.next\"\n")
	assert.Contains(t, src, "\tMinVersion = \"2.0.0-alpha.1\"\n")
	assert.Contains(t, src, "\tFingerprintScheme = \""+scheme+"\"\n")
	assert.Contains(t, src, "var Fingerprints = map[string]string{\n"+
		"\t\"crds\":            \""+fps["crds"]+"\",\n"+
		"\t\"http-api\":        \""+fps["http-api"]+"\",\n"+
		"\t\"storage-classes\": \""+fps["storage-classes"]+"\",\n"+
		"\t\"go-api\":          \""+fps["go-api"]+"\",\n"+
		"\t\"changes\":         \""+fps["changes"]+"\",\n}\n")
	assert.Contains(t, src, "var UpgradableFrom = []string{}\n")

	// The generated file is not an input, so running again changes nothing.
	require.NoError(t, run(root))
	assert.Equal(t, src, readFile(t, root, outputPath))
}

// TestRunRelease checks the window of a core whose contract is the one its
// latest release was cut with.
func TestRunRelease(t *testing.T) {
	t.Parallel()

	files := testRepo()
	files[releasesDir+"/2.0.0-alpha.2.yaml"] = record("2.0.0-alpha.2", "2.0.0-alpha.2", "2.0.0-alpha.1", "upgradable", "[2.0.0-alpha.1, 2.0.0-alpha.1.1]", testFingerprints(t, files))
	root := writeRepo(t, files)
	var notices bytes.Buffer
	require.NoError(t, generate(root, &notices))
	assert.Empty(t, notices.String())
	assert.Equal(t, "2.0.0-alpha.2\n", readFile(t, root, versionFile))
	assert.Equal(t, "2.0.0-alpha.1\n", readFile(t, root, minVersionFile))
	assert.Contains(t, readFile(t, root, outputPath), "var UpgradableFrom = []string{\"2.0.0-alpha.1\", \"2.0.0-alpha.1.1\"}\n")

	// A pre-release may change the contract, so a release branch after one
	// passes either way.
	msg, err := execute([]string{"-root", root, "-check-release", "-branch", "release-2.0"}, io.Discard, io.Discard)
	require.NoError(t, err)
	assert.Contains(t, msg, "is not a patch release of 2.0.0-alpha.2")

	// A change to the contract after the release moves the version to the
	// development value, and says why.
	require.NoError(t, os.WriteFile(filepath.Join(root, filepath.FromSlash(changesFile)), []byte(testChanges+"- #1: a change.\n"), 0o600))
	notices.Reset()
	require.NoError(t, generate(root, &notices))
	assert.Equal(t, "2.0.0-alpha.2.next\n", readFile(t, root, versionFile))
	assert.Contains(t, readFile(t, root, outputPath), "var UpgradableFrom = []string{}\n")
	assert.Equal(t, "gen-contract: contract version 2.0.0-alpha.2.next: the contract changed since release 2.0.0-alpha.2: "+
		"changes differs from its record (fingerprint scheme "+scheme+"); make contract-diff shows how\n", notices.String(),
	)
}

// TestCheckReleaseCommand checks -check-release on a branch whose latest
// release is final, which a patch release must keep the contract of.
func TestCheckReleaseCommand(t *testing.T) {
	t.Parallel()

	files := testRepo()
	files[releasesDir+"/2.1.0.yaml"] = record("2.1.0", "2.1.0", "2.1.0", "fresh-install", "[]", with(testFingerprints(t, files), "go-api", ""))
	root := writeRepo(t, files)
	var notices bytes.Buffer
	for _, args := range [][]string{{"-version", "2.1.1"}, {"-branch", "release-2.1"}} {
		notices.Reset()
		msg, err := execute(append([]string{"-root", root, "-check-release"}, args...), io.Discard, &notices)
		require.NoError(t, err, args)
		assert.Equal(t, "the contract is the one release 2.1.0 was cut with (crds, http-api, storage-classes, changes equal under fingerprint scheme "+scheme+")", msg)
		assert.Contains(t, notices.String(), "not compared: go-api", "the message names what it skipped")
	}

	msg, err := execute([]string{"-root", root, "-check-release", "-branch", "main"}, io.Discard, io.Discard)
	require.NoError(t, err)
	assert.Equal(t, "main is not a release branch release-X.Y, so no release cut from it is a patch release", msg)

	replace(t, files, crdPath, "maximum: 10", "maximum: 9")
	root = writeRepo(t, files)
	notices.Reset()
	_, err = execute([]string{"-root", root, "-check-release", "-version", "2.1.1"}, io.Discard, &notices)
	require.ErrorContains(t, err, "the contract changed since release 2.1.0: crds differs from its record")
	assert.Contains(t, notices.String(), "fetch v2.1.0 to see the diff", "the test repository has no tag")

	msg, err = execute([]string{"-root", root, "-check-release", "-version", "2.2.0"}, io.Discard, io.Discard)
	require.NoError(t, err, "a minor release may change the contract")
	assert.Contains(t, msg, "is not a patch release of 2.1.0")
}

