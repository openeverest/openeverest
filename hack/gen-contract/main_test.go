const testHeader = "// Header.\n"

// contractDir writes a contract package directory with the given VERSION and
// MIN_VERSION content, and a header file, and returns their paths.
func contractDir(t *testing.T, version, minVersion string) (string, string) {
	t.Helper()

	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, versionFile), []byte(version), 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(dir, minVersionFile), []byte(minVersion), 0o600))
	header := filepath.Join(t.TempDir(), "header.txt")
	require.NoError(t, os.WriteFile(header, []byte(testHeader), 0o600))
	return dir, header
}

func readGenerated(t *testing.T, dir string) string {
	t.Helper()

	data, err := os.ReadFile(filepath.Join(dir, outputFile)) //nolint:gosec // the output of the generator under test
	require.NoError(t, err)
	return string(data)
}

func TestRender(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name       string
		version    string
		minVersion string
		wantErr    string
	}{
		{name: "window", version: "2.1.0-alpha.1.next\n", minVersion: "2.0.0\n"},
		{name: "single version", version: "2.0.0\n", minVersion: "2.0.0\n"},
		{name: "no trailing newline", version: "2.0.0", minVersion: "2.0.0"},
		{name: "minimum above version", version: "2.0.0\n", minVersion: "2.1.0\n", wantErr: "MIN_VERSION 2.1.0 is above VERSION 2.0.0"},
		{name: "development minimum above its release", version: "2.0.0\n", minVersion: "2.1.0-alpha.0\n", wantErr: "is above"},
		{name: "v prefix", version: "v2.0.0\n", minVersion: "2.0.0\n", wantErr: `VERSION: "v2.0.0" is not a SemVer 2.0.0 version`},
		{name: "short form", version: "2.0.0\n", minVersion: "2.0\n", wantErr: `MIN_VERSION: "2.0" is not a SemVer 2.0.0 version`},
		{name: "empty", version: "", minVersion: "2.0.0\n", wantErr: `VERSION: "" is not a SemVer 2.0.0 version`},
		{name: "two lines", version: "2.0.0\n2.1.0\n", minVersion: "2.0.0\n", wantErr: "must hold a single line"},
		{name: "blank line", version: "2.0.0\n\n", minVersion: "2.0.0\n", wantErr: "must hold a single line"},
		{name: "carriage return", version: "2.0.0\r\n", minVersion: "2.0.0\n", wantErr: "is not a SemVer 2.0.0 version"},
		{name: "surrounding space", version: " 2.0.0\n", minVersion: "2.0.0\n", wantErr: "is not a SemVer 2.0.0 version"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir, header := contractDir(t, tt.version, tt.minVersion)
			src, err := render(dir, header)
			if tt.wantErr != "" {
				require.ErrorContains(t, err, tt.wantErr)
				return
			}
			require.NoError(t, err)
			assert.Contains(t, string(src), testHeader+"\n// Code generated by hack/gen-contract. DO NOT EDIT.\n\npackage contract\n")
		})
	}
}

func TestRenderValues(t *testing.T) {
	t.Parallel()

	dir, header := contractDir(t, "2.1.0-alpha.1.next\n", "2.0.0\n")
	src, err := render(dir, header)
	require.NoError(t, err)
	assert.Contains(t, string(src), "\tVersion = \"2.1.0-alpha.1.next\"\n")
	assert.Contains(t, string(src), "\tMinVersion = \"2.0.0\"\n")
}

func TestRenderMissingFiles(t *testing.T) {
	t.Parallel()

	_, err := render(t.TempDir(), filepath.Join("..", "boilerplate.go.txt"))
	require.ErrorIs(t, err, os.ErrNotExist)

	dir, _ := contractDir(t, "2.0.0\n", "2.0.0\n")
	_, err = render(dir, filepath.Join(dir, "missing.txt"))
	require.ErrorIs(t, err, os.ErrNotExist)
}

func TestRunIsIdempotent(t *testing.T) {
	t.Parallel()

	dir, header := contractDir(t, "2.0.0-alpha.1.next\n", "2.0.0-alpha.1\n")
	require.NoError(t, run(dir, header))
	first := readGenerated(t, dir)
	require.NoError(t, run(dir, header))
	assert.Equal(t, first, readGenerated(t, dir))
}

// TestGeneratedFileIsUpToDate fails when contract/VERSION or
// contract/MIN_VERSION changed without make gen-contract.
func TestGeneratedFileIsUpToDate(t *testing.T) {
	t.Parallel()

	dir := filepath.Join("..", "..", "contract")
	want, err := render(dir, filepath.Join("..", "boilerplate.go.txt"))
	require.NoError(t, err)
	assert.Equal(t, string(want), readGenerated(t, dir), "run make gen-contract")
}
