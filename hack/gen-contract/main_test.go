func readFile(t *testing.T, root, name string) string {
	t.Helper()

	data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(name))) //nolint:gosec // a file the test wrote
	require.NoError(t, err)
	return string(data)
}

func TestRun(t *testing.T) {
	t.Parallel()

	root := writeRepo(t, testRepo())
	require.NoError(t, run(root))
	assert.Equal(t, "2.0.0-alpha.1.next\n", readFile(t, root, versionFile))
	assert.Equal(t, "2.0.0-alpha.1\n", readFile(t, root, minVersionFile))

	src := readFile(t, root, outputPath)
	fp := testFingerprint(t, testRepo())
	assert.True(t, strings.HasPrefix(src, testHeader+"\n// Code generated by hack/gen-contract. DO NOT EDIT.\n\npackage contract\n"))
	assert.Contains(t, src, "\tVersion = \"2.0.0-alpha.1.next\"\n")
	assert.Contains(t, src, "\tMinVersion = \"2.0.0-alpha.1\"\n")
	assert.Contains(t, src, "\tFingerprint = \""+fp+"\"\n")
	assert.Contains(t, src, "var UpgradableFrom = []string{}\n")

	// The generated file is not an input, so running again changes nothing.
	require.NoError(t, run(root))
	assert.Equal(t, src, readFile(t, root, outputPath))
}

// TestRunRelease checks the window of a core whose contract is the one its
// latest release was cut with.
func TestRunRelease(t *testing.T) {
	t.Parallel()

	files := testRepo()
	fp := testFingerprint(t, files)
	files[releasesDir+"/2.0.0-alpha.2.yaml"] = record("2.0.0-alpha.2", "2.0.0-alpha.2", "2.0.0-alpha.1", "upgradable", "[2.0.0-alpha.1, 2.0.0-alpha.1.1]", fp)
	root := writeRepo(t, files)
	require.NoError(t, run(root))
	assert.Equal(t, "2.0.0-alpha.2\n", readFile(t, root, versionFile))
	assert.Equal(t, "2.0.0-alpha.1\n", readFile(t, root, minVersionFile))
	assert.Contains(t, readFile(t, root, outputPath), "var UpgradableFrom = []string{\"2.0.0-alpha.1\", \"2.0.0-alpha.1.1\"}\n")

	msg, err := runCheckRelease(root)
	require.NoError(t, err)
	assert.Equal(t, "the contract is the one release 2.0.0-alpha.2 was cut with ("+fp+")", msg)

	// A change to the contract after the release moves the version to the
	// development value and fails the release check.
	require.NoError(t, os.WriteFile(filepath.Join(root, filepath.FromSlash(changesFile)), []byte("Changes no artifact shows.\n#1: a change.\n"), 0o600))
	require.NoError(t, run(root))
	assert.Equal(t, "2.0.0-alpha.2.next\n", readFile(t, root, versionFile))
	assert.Contains(t, readFile(t, root, outputPath), "var UpgradableFrom = []string{}\n")
	_, err = runCheckRelease(root)
	require.ErrorContains(t, err, "the contract changed since release 2.0.0-alpha.2")
}

// TestRunWithBrokenContractPackage checks that the command runs whatever
// state the file it generates is in.
func TestRunWithBrokenContractPackage(t *testing.T) {
	t.Parallel()

	files := testRepo()
	files[outputPath] = "package contract\n\nconst Version = \n"
	root := writeRepo(t, files)
	require.NoError(t, run(root))
	assert.Contains(t, readFile(t, root, outputPath), "\tVersion = \"2.0.0-alpha.1.next\"\n")
}

func TestRunErrors(t *testing.T) {
	t.Parallel()

	files := testRepo()
	delete(files, releasesDir+"/2.0.0-alpha.1.yaml")
	require.ErrorContains(t, run(writeRepo(t, files)), "holds no release record")

	files = testRepo()
	delete(files, headerFile)
	require.ErrorIs(t, run(writeRepo(t, files)), os.ErrNotExist)
}

// TestImportsNothingFromThisModule keeps the command independent of the
// contract package it generates, so a missing or broken generated file
// cannot stop it from regenerating that file.
func TestImportsNothingFromThisModule(t *testing.T) {
	t.Parallel()

	files, err := filepath.Glob("*.go")
	require.NoError(t, err)
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.ImportsOnly)
		require.NoError(t, err)
		for _, imp := range f.Imports {
			path, err := strconv.Unquote(imp.Path.Value)
			require.NoError(t, err)
			assert.False(t, strings.HasPrefix(path, "github.com/openeverest/openeverest/v2"), "%s imports %s", file, path)
		}
	}
}

// TestGeneratedFilesAreUpToDate fails when the contract changed without
// make gen-contract.
func TestGeneratedFilesAreUpToDate(t *testing.T) {
	t.Parallel()

	root := filepath.Join("..", "..")
	w, err := compute(root)
	require.NoError(t, err)
	src, err := render(root, w)
	require.NoError(t, err)
	assert.Equal(t, string(src), readFile(t, root, outputPath), "run make gen-contract")
	assert.Equal(t, w.version+"\n", readFile(t, root, versionFile), "run make gen-contract")
	assert.Equal(t, w.minVersion+"\n", readFile(t, root, minVersionFile), "run make gen-contract")
}
