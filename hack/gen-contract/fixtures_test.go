// writeRepo writes files to a new directory and returns it.
func writeRepo(t *testing.T, files map[string]string) string {
	t.Helper()

	root := t.TempDir()
	for name, content := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o750))
		require.NoError(t, os.WriteFile(path, []byte(content), 0o600))
	}
	return root
}

// replace replaces old with replacement in the file at path, which must
// hold old.
func replace(t *testing.T, files map[string]string, path, old, replacement string) {
	t.Helper()

	require.Contains(t, files[path], old, "fixture %s", path)
	files[path] = strings.ReplaceAll(files[path], old, replacement)
}

func cloneRepo(files map[string]string) map[string]string {
	return maps.Clone(files)
}
