const header = "# Code generated by hack/gen-backupstorageclasses. DO NOT EDIT.\n"

// Keys of the uiSchema the ui-generator renders.
const (
	keyComponents      = "components"
	keyComponentsOrder = "componentsOrder"
	keyFieldParams     = "fieldParams"
	keyLabel           = "label"
	keyPath            = "path"
	keyPlaceholder     = "placeholder"
	keyUIType          = "uiType"
	keyValue           = "value"
)

type class struct {
	name        string
	schemaKind  string
	displayName string
	description string
	authModes   []map[string]any
	uiSchema    map[string]any
}

func textField(path, label string, extra map[string]any, required bool) map[string]any {
	params := map[string]any{keyLabel: label}
	maps.Copy(params, extra)
	field := map[string]any{keyPath: path, keyUIType: "text", keyFieldParams: params}
	if required {
		field["validation"] = map[string]any{"required": true}
	}
	return field
}

