func main() {
	crdDir := flag.String("crd-dir", "", "directory holding the CRDs controller-gen rendered for _schema")
	out := flag.String("out", "config/backupstorageclasses", "output directory")
	flag.Parse()
	if err := run(*crdDir, *out); err != nil {
		log.Fatal(err)
	}
}

func run(crdDir, out string) error {
	if err := os.MkdirAll(out, 0o750); err != nil {
		return err
	}
	classes := builtinClasses()
	resources := make([]string, 0, len(classes))
	for _, c := range classes {
		schema, err := parametersSchema(crdDir, c.schemaKind)
		if err != nil {
			return fmt.Errorf("class %s: %w", c.name, err)
		}
		obj := map[string]any{
			"apiVersion": "backup.openeverest.io/v1alpha1",
			"kind":       "BackupStorageClass",
			"metadata":   map[string]any{"name": c.name},
			"spec": map[string]any{
				"displayName":      c.displayName,
				"description":      c.description,
				"parametersSchema": map[string]any{"openAPIV3Schema": schema},
				"authModes":        c.authModes,
				"uiSchema":         c.uiSchema,
			},
		}
		data, err := yaml.Marshal(obj)
		if err != nil {
			return err
		}
		file := c.name + ".yaml"
		if err := os.WriteFile(filepath.Join(out, file), append([]byte(header), data...), 0o600); err != nil {
			return err
		}
		resources = append(resources, file)
	}
	kustomization, err := yaml.Marshal(map[string]any{
		"apiVersion": "kustomize.config.k8s.io/v1beta1",
		"kind":       "Kustomization",
		"resources":  resources,
	})
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(out, "kustomization.yaml"), append([]byte(header), kustomization...), 0o600)
}

// parametersSchema returns the spec schema of the wrapper CRD for kind.
func parametersSchema(crdDir, kind string) (*apiextensionsv1.JSONSchemaProps, error) {
	file := filepath.Join(crdDir, "schema.backupstorageclasses.openeverest.io_"+strings.ToLower(kind)+"s.yaml")
	data, err := os.ReadFile(file) //nolint:gosec // a file controller-gen wrote for this generator
	if err != nil {
		return nil, err
	}
	crd := &apiextensionsv1.CustomResourceDefinition{}
	if err := yaml.UnmarshalStrict(data, crd); err != nil {
		return nil, fmt.Errorf("%s: %w", file, err)
	}
	if len(crd.Spec.Versions) != 1 || crd.Spec.Versions[0].Schema == nil {
		return nil, fmt.Errorf("%s: expected one version with a schema", file)
	}
	spec, ok := crd.Spec.Versions[0].Schema.OpenAPIV3Schema.Properties["spec"]
	if !ok {
		return nil, fmt.Errorf("%s: no spec schema", file)
	}
	spec.Description = ""
	if err := rejectCEL("spec", &spec); err != nil {
		return nil, err
	}
	return &spec, nil
}

// rejectCEL fails on x-kubernetes-validations: parameters are validated by
// gojsonschema, which cannot evaluate them.
func rejectCEL(path string, s *apiextensionsv1.JSONSchemaProps) error {
	if len(s.XValidations) > 0 {
		return fmt.Errorf("%s: class parameter types must not carry XValidation markers", path)
	}
	var errs []error
	for name, p := range s.Properties {
		errs = append(errs, rejectCEL(path+"."+name, &p))
	}
	if s.Items != nil && s.Items.Schema != nil {
		errs = append(errs, rejectCEL(path+"[]", s.Items.Schema))
	}
	if s.AdditionalProperties != nil && s.AdditionalProperties.Schema != nil {
		errs = append(errs, rejectCEL(path+"{}", s.AdditionalProperties.Schema))
	}
	return errors.Join(errs...)
}
