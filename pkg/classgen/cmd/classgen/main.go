// Command classgen generates what an integration's class manifests take from
// OpenEverest core (see package classgen). Run it as `go tool classgen` from
// the integration's module, which requires it as a tool:
//
//	go get -tool github.com/openeverest/openeverest/v2/pkg/classgen/cmd/classgen@<version>
//
// That builds it against the OpenEverest core the module requires, which is
// what it writes for. Each form first checks that it links that core, and
// refuses to run when it does not, as happens to `go run` of a versioned
// package or to a separately installed binary once the version drifts from
// go.mod.
//
// The first form prints the OpenAPI v3 schema of a class parameters type as
// YAML, with its markers, for the class to publish:
//
//	classgen --package . --type Parameters [--output zz_generated.parameters.yaml]
//
// stamp stamps the integration's chart with the contract version of that
// core, the oldest OpenEverest the build works with, which it prints: the
// openeverest.io/contract-version annotation in Chart.yaml, and the helper
// template the MonitoringClass and the other objects OpenEverest interprets
// include to carry it:
//
//	classgen stamp --chart-dir charts/<name>
//
// verify checks that Chart.yaml and every object OpenEverest interprets that
// the chart renders with its default values carry that stamp. With
// --release, it also fails when the stamp is a development value, which
// names an OpenEverest users cannot install, or when go.mod replaces the
// core:
//
//	classgen verify --chart-dir charts/<name> [--release]
package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"strings"

	"sigs.k8s.io/yaml"

	"github.com/openeverest/openeverest/v2/contract"
	"github.com/openeverest/openeverest/v2/pkg/classgen"
)

const header = "# Code generated by classgen. DO NOT EDIT.\n"

const usage = `Usage:
  go tool classgen --package <pattern> --type <name> [--output <file>]
  go tool classgen stamp --chart-dir <dir>
  go tool classgen verify --chart-dir <dir> [--release]
`

func main() {
	ctx := context.Background()
	check := func() (module, string, error) { return checkLinkedCore(ctx) }
	err := run(os.Args[1:], os.Stdout, os.Stderr, check)
	switch {
	case errors.Is(err, flag.ErrHelp):
	case err != nil:
		fmt.Fprintln(os.Stderr, "classgen:", err)
		os.Exit(1)
	}
}

// coreCheck returns the core the module classgen runs in requires, after
// checking it is the one classgen links, and a warning to print, if any.
type coreCheck func() (required module, warning string, err error)

func run(args []string, stdout, stderr io.Writer, check coreCheck) error {
	if len(args) > 0 {
		switch args[0] {
		case "stamp":
			return runStamp(args[1:], stderr, check)
		case "verify":
			return runVerify(args[1:], stderr, check)
		}
	}
	return runSchema(args, stdout, stderr, check)
}

// packageFlags collects the repeated --package flag.
type packageFlags []string

func (p *packageFlags) String() string { return strings.Join(*p, ",") }

func (p *packageFlags) Set(v string) error {
	*p = append(*p, v)
	return nil
}

func runSchema(args []string, stdout, stderr io.Writer, check coreCheck) error {
	flags := newFlagSet("classgen", stderr)
	var pkgs packageFlags
	flags.Var(&pkgs, "package", "package pattern holding the type, such as . or ./api; repeatable")
	typeName := flags.String("type", "", "name of the parameters type")
	output := flags.String("output", "", "file to write the schema to (default: standard output)")
	if err := parse(flags, args); err != nil {
		return err
	}
	if len(pkgs) == 0 || *typeName == "" {
		return errors.New("--package and --type are required")
	}
	if _, err := runCoreCheck(stderr, check); err != nil {
		return err
	}

	schema, err := classgen.Schema(pkgs, *typeName)
	if err != nil {
		return err
	}
	data, err := yaml.Marshal(schema)
	if err != nil {
		return err
	}
	data = append([]byte(header), data...)
	if *output == "" {
		_, err := stdout.Write(data)
		return err
	}
	return os.WriteFile(*output, data, 0o600)
}

func runStamp(args []string, stderr io.Writer, check coreCheck) error {
	flags := newFlagSet("classgen stamp", stderr)
	chartDir := flags.String("chart-dir", "", "the integration's chart directory, such as charts/monitoring-pmm")
	if err := parse(flags, args); err != nil {
		return err
	}
	if *chartDir == "" {
		return errors.New("--chart-dir is required")
	}
	if _, err := runCoreCheck(stderr, check); err != nil {
		return err
	}

	res, err := classgen.StampChart(*chartDir, contract.Version)
	if err != nil {
		return err
	}
	for _, file := range res.Written {
		if file != "Chart.yaml" {
			fmt.Fprintf(stderr, "Generated: %s\n", joinChart(*chartDir, file))
			continue
		}
		was := ""
		if res.Previous != "" {
			was = ", was " + res.Previous
		}
		fmt.Fprintf(stderr, "Stamped: %s (%s=%s%s)\n", joinChart(*chartDir, file), contract.VersionAnnotation, contract.Version, was)
	}
	fmt.Fprintln(stderr, floor(contract.Version))
	return nil
}

func runVerify(args []string, stderr io.Writer, check coreCheck) error {
	flags := newFlagSet("classgen verify", stderr)
	chartDir := flags.String("chart-dir", "", "the integration's chart directory, such as charts/monitoring-pmm")
	release := flags.Bool("release", false, "also fail when the integration is built against an unreleased OpenEverest")
	if err := parse(flags, args); err != nil {
		return err
	}
	if *chartDir == "" {
		return errors.New("--chart-dir is required")
	}
	required, err := runCoreCheck(stderr, check)
	if err != nil {
		return err
	}

	res, err := classgen.VerifyChart(*chartDir, contract.Version)
	if err != nil {
		return err
	}
	if *release {
		res.Problems = append(res.Problems, releaseProblems(required, contract.Version)...)
	}
	if len(res.Stamped) > 0 {
		fmt.Fprintf(stderr, "Stamped with %s=%s:\n", contract.VersionAnnotation, contract.Version)
		for _, s := range res.Stamped {
			fmt.Fprintf(stderr, "  %s\n", s)
		}
	}
	if len(res.Problems) > 0 {
		var b strings.Builder
		fmt.Fprintf(&b, "%d problem(s) in %s:", len(res.Problems), *chartDir)
		for _, p := range res.Problems {
			fmt.Fprintf(&b, "\n  - %s", p)
		}
		return errors.New(b.String())
	}
	fmt.Fprintln(stderr, floor(contract.Version))
	return nil
}

func newFlagSet(name string, stderr io.Writer) *flag.FlagSet {
	flags := flag.NewFlagSet(name, flag.ContinueOnError)
	flags.SetOutput(stderr)
	flags.Usage = func() {
		fmt.Fprint(stderr, usage)
		flags.PrintDefaults()
	}
	return flags
}

func parse(flags *flag.FlagSet, args []string) error {
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() > 0 {
		return fmt.Errorf("unexpected arguments: %s", strings.Join(flags.Args(), " "))
	}
	return nil
}

// runCoreCheck runs check, printing its warning to stderr.
func runCoreCheck(stderr io.Writer, check coreCheck) (module, error) {
	required, warning, err := check()
	if err != nil {
		return module{}, err
	}
	if warning != "" {
		fmt.Fprintf(stderr, "Warning: %s\n", warning)
	}
	return required, nil
}

// joinChart names file, relative to the chart in chartDir, as the user
// would.
func joinChart(chartDir, file string) string {
	return strings.TrimSuffix(chartDir, "/") + "/" + file
}
