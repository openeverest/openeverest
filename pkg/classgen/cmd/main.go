// Command classgen prints the OpenAPI v3 schema of a class parameters type as
// YAML (see package classgen). Run it from the module of the type:
//
//	go run github.com/openeverest/openeverest/v2/pkg/classgen/cmd@<version> \
//		--package . --type Parameters --output zz_generated.parameters.yaml
package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"strings"

	"sigs.k8s.io/yaml"

	"github.com/openeverest/openeverest/v2/pkg/classgen"
)

const header = "# Code generated by classgen. DO NOT EDIT.\n"

func main() {
	err := run(os.Args[1:], os.Stdout, os.Stderr)
	switch {
	case errors.Is(err, flag.ErrHelp):
	case err != nil:
		fmt.Fprintln(os.Stderr, "classgen:", err)
		os.Exit(1)
	}
}

// packageFlags collects the repeated --package flag.
type packageFlags []string

func (p *packageFlags) String() string { return strings.Join(*p, ",") }

func (p *packageFlags) Set(v string) error {
	*p = append(*p, v)
	return nil
}

func run(args []string, stdout, stderr io.Writer) error {
	flags := flag.NewFlagSet("classgen", flag.ContinueOnError)
	flags.SetOutput(stderr)
	var pkgs packageFlags
	flags.Var(&pkgs, "package", "package pattern holding the type, such as . or ./api; repeatable")
	typeName := flags.String("type", "", "name of the parameters type")
	output := flags.String("output", "", "file to write the schema to (default: standard output)")
	if err := flags.Parse(args); err != nil {
		return err
	}
	switch {
	case len(pkgs) == 0 || *typeName == "":
		return errors.New("--package and --type are required")
	case flags.NArg() > 0:
		return fmt.Errorf("unexpected arguments: %s", strings.Join(flags.Args(), " "))
	}

	schema, err := classgen.Schema(pkgs, *typeName)
	if err != nil {
		return err
	}
	data, err := yaml.Marshal(schema)
	if err != nil {
		return err
	}
	data = append([]byte(header), data...)
	if *output == "" {
		_, err := stdout.Write(data)
		return err
	}
	return os.WriteFile(*output, data, 0o600)
}
